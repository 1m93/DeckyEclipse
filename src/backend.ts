import { callable } from "@decky/api";
import type {
  AppsStatus,
  AppUpdateCheck,
  DiagnosticCheck,
  DiscoveredHost,
  DisplayInfo,
  EndSessionResult,
  Feature,
  Host,
  HostConfig,
  HostDisplay,
  HostStatus,
  InitialState,
  InstallResult,
  LibraryEntryResult,
  MonitorRefresh,
  MoonlightInfo,
  PairedClient,
  PairOutcome,
  PairResult,
  PendingPairing,
  Patch,
  PluginUpdateCheck,
  Preset,
  QuitResult,
  Result,
  Settings,
  StreamPrepareResult,
  SunshineDiagnostics,
  SunshineLoginState,
  SunshineOptions,
  SunshineOptionsResult,
  SunshineOverview,
  SunshineSession,
  SunshineStatus,
} from "./types";

/** Typed bindings for every method exposed by the Python `Plugin` class. */
export const backend = {
  getState: callable<[], InitialState>("get_state"),
  getDisplay: callable<[], { display: DisplayInfo; presets: Preset[] }>("get_display"),
  getHosts: callable<[], Host[]>("get_hosts"),
  probeHosts: callable<[force: boolean], Record<string, HostStatus>>("probe_hosts"),
  updateSettings: callable<[patch: Patch<Settings>], Settings>("update_settings"),
  setHostConfig: callable<[uuid: string, patch: Patch<HostConfig> | null], Result & { settings: Settings }>(
    "set_host_config",
  ),
  refreshMoonlight: callable<[], MoonlightInfo>("refresh_moonlight"),
  discoverHosts: callable<[], Result & { items: DiscoveredHost[]; scanned: boolean }>("discover_hosts"),

  wakeHost: callable<[uuid: string], Result>("wake_host"),
  prepareStream: callable<[uuid: string, appName: string], StreamPrepareResult>("prepare_stream"),
  prepareGui: callable<[], Result>("prepare_gui"),
  preparePair: callable<
    [address: string, uuid: string | null, creds: Partial<HostConfig> | null],
    PairResult
  >("prepare_pair"),
  prepareQuit: callable<[uuid: string], QuitResult>("prepare_quit"),
  stopStream: callable<[], void>("stop_stream"),
  quitAfterStream: callable<[uuid: string], QuitResult>("quit_after_stream"),
  testHostCredentials: callable<[uuid: string], Result>("test_host_credentials"),
  hostDiagnostics: callable<[uuid: string], Result & { checks: DiagnosticCheck[] }>("host_diagnostics"),
  detectHostDisplays: callable<[uuid: string], Result & { displays: HostDisplay[] }>("detect_host_displays"),
  hostCurrentDisplay: callable<[uuid: string], Result & { current: string | null }>("host_current_display"),
  refreshHostMonitors: callable<[uuid: string, rescan: boolean], MonitorRefresh>("refresh_host_monitors"),

  addLibraryEntry: callable<[uuid: string, appName: string], LibraryEntryResult>("add_library_entry"),
  setLibraryAppId: callable<[entryId: string, steamAppId: number], void>("set_library_app_id"),
  removeLibraryEntry: callable<[entryId: string], void>("remove_library_entry"),
  getBoxart: callable<[uuid: string, appId: string], string | null>("get_boxart"),

  installMoonlight: callable<[], InstallResult>("install_moonlight"),
  installSunshine: callable<[password: string], InstallResult>("install_sunshine"),
  repairSunshine: callable<[password: string], InstallResult>("repair_sunshine"),
  uninstallSunshineFlatpak: callable<[deleteData: boolean], InstallResult>("uninstall_sunshine_flatpak"),
  cancelInstall: callable<[], Result>("cancel_install"),
  appsStatus: callable<[], AppsStatus>("apps_status"),
  checkAppUpdate: callable<[feature: Feature], AppUpdateCheck>("check_app_update"),
  /** `password`: sudo password, needed for Sunshine for Gaming Mode only. */
  updateApp: callable<[feature: Feature, password: string | null], InstallResult>("update_app"),
  uninstallApp: callable<[feature: Feature, deleteData: boolean, password: string | null], InstallResult>(
    "uninstall_app",
  ),
  checkPluginUpdate: callable<[], PluginUpdateCheck>("check_plugin_update"),
  sudoPasswordState: callable<[], { state: "set" | "none" | "unknown" }>("sudo_password_state"),
  createSudoPassword: callable<[password: string], Result>("create_sudo_password"),

  sunshineStatus: callable<[], SunshineStatus>("sunshine_status"),
  sunshineStart: callable<[], Result>("sunshine_start"),
  sunshineStop: callable<[], Result>("sunshine_stop"),
  sunshineRestart: callable<[], Result>("sunshine_restart"),
  sunshineGetOptions: callable<[], SunshineOptionsResult>("sunshine_get_options"),
  sunshineSetOptions: callable<[patch: Partial<SunshineOptions>], SunshineOptionsResult>("sunshine_set_options"),
  sunshineSetAutostart: callable<[enabled: boolean], Result>("sunshine_set_autostart"),
  sunshineSubmitPin: callable<[pin: string, clientName: string, pairingId: string | null], PairOutcome>(
    "sunshine_submit_pin",
  ),
  sunshinePendingPairings: callable<[], Result & { supported: boolean; items: PendingPairing[] }>(
    "sunshine_pending_pairings",
  ),
  sunshineClients: callable<[], Result & { items: PairedClient[] }>("sunshine_clients"),
  sunshineUnpair: callable<[uuid: string], Result>("sunshine_unpair"),
  pairingOutcome: callable<[address: string], { paired: boolean; host: string | null }>("pairing_outcome"),
  sunshineTestLogin: callable<[], Result>("sunshine_test_login"),
  sunshineLoginState: callable<[], { state: SunshineLoginState; error: string | null }>("sunshine_login_state"),
  sunshineCreateLogin: callable<[user: string, password: string], Result>("sunshine_create_login"),
  sunshineCreateLoginAuto: callable<[], Result & { user: string | null; password: string | null }>(
    "sunshine_create_login_auto",
  ),
  sunshineRevealLogin: callable<[], Result & { user: string | null; password: string | null }>("sunshine_reveal_login"),
  sunshineDiagnostics: callable<[], SunshineDiagnostics>("sunshine_diagnostics"),
  sunshineSession: callable<[], SunshineSession>("sunshine_session"),
  /** `restart`: restart Sunshine instead of closing the open app. */
  sunshineEndSession: callable<[restart: boolean], EndSessionResult>("sunshine_end_session"),
  sunshineOverview: callable<[], SunshineOverview>("sunshine_overview"),
  getSunshineLog: callable<[], string>("get_sunshine_log"),

  getLauncherLog: callable<[], string>("get_launcher_log"),
  getPluginLog: callable<[], string>("get_plugin_log"),
};

